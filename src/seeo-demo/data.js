export const windows = { shift: [0, 480], morning: [0, 240], late: [240, 480] };
export function eventsInWindow(key) {
  const [start, end] = windows[key] ?? windows.shift;
  return events.filter(
    (event) => event.minutes >= start && event.minutes < end,
  );
}
export function areaCamera(id) {
  return cameras.find(
    (camera) => camera.id === areas.find((area) => area.id === id)?.camera,
  );
}
